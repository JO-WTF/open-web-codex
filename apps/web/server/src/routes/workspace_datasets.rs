type ApiError = (StatusCode, Json<PlatformError>);
type ApiResult<T> = Result<Json<T>, ApiError>;

const MAX_METADATA_BYTES: usize = 64 * 1024;
const MAX_FILES: usize = 32;
const MAX_FILE_BYTES: usize = 32 * 1024 * 1024;
const MAX_TOTAL_FILE_BYTES: usize = 64 * 1024 * 1024;
const PUBLISHING_RECOVERY_AFTER_MINUTES: i64 = 5;

#[derive(Debug)]
struct UploadedPart {
    bytes: Vec<u8>,
}

#[derive(Debug)]
struct PreparedFile {
    descriptor: WorkspaceDatasetUploadFile,
    bytes: Vec<u8>,
    content_sha256: String,
}

#[derive(Debug)]
struct ReleaseRecord {
    id: Uuid,
    workspace_id: Uuid,
    dataset_id: String,
    version: String,
    state: String,
    content_sha256: String,
    updated_at: DateTime<Utc>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum ExistingReleaseAction {
    ReturnPublished,
    FinalizePublished,
    RetryPublication,
    PublicationInProgress,
    PublishedContentUnavailable,
    InvalidLifecycle,
}

pub async fn list(
    State(state): State<AppState>,
    auth: AuthenticatedUser,
    Path(workspace_id): Path<Uuid>,
) -> ApiResult<Vec<WorkspaceDatasetReleaseSummary>> {
    let workspace_id = authorized_workspace(&state, &auth, workspace_id, false).await?;
    let ids = sqlx::query(
        "SELECT id FROM workspace_dataset_releases \
         WHERE organization_id = $1 AND workspace_id = $2 \
         ORDER BY created_at DESC, id DESC LIMIT 100",
    )
    .bind(auth.organization_id)
    .bind(workspace_id)
    .fetch_all(&state.db)
    .await
    .map_err(database_error)?
    .into_iter()
    .map(|row| row.get::<Uuid, _>("id"))
    .collect::<Vec<_>>();
    let mut releases = Vec::with_capacity(ids.len());
    for release_id in ids {
        releases.push(
            load_release(&state, &auth, workspace_id, release_id)
                .await?
                .ok_or_else(|| internal("Dataset Release disappeared while listing"))?,
        );
    }
    Ok(Json(releases))
}

pub async fn get(
    State(state): State<AppState>,
    auth: AuthenticatedUser,
    Path((workspace_id, release_id)): Path<(Uuid, Uuid)>,
) -> ApiResult<WorkspaceDatasetReleaseSummary> {
    let workspace_id = authorized_workspace(&state, &auth, workspace_id, false).await?;
    let release = load_release(&state, &auth, workspace_id, release_id)
        .await?
        .ok_or_else(|| not_found("Dataset Release was not found"))?;
    Ok(Json(release))
}

pub async fn publish(
    State(state): State<AppState>,
    auth: AuthenticatedUser,
    Path(workspace_id): Path<Uuid>,
    Extension(git): Extension<Arc<GitRuntime>>,
    multipart: Multipart,
) -> ApiResult<WorkspaceDatasetReleaseSummary> {
    let workspace_id = authorized_workspace(&state, &auth, workspace_id, true).await?;
    let (request, uploaded) = parse_multipart(multipart).await?;
    validate_request(&request, &uploaded)?;
    let prepared = prepare_files(&request, uploaded)?;
    publish_prepared_release(&state, &auth, workspace_id, &git, request, prepared)
        .await
        .map(Json)
}

/// Publish a server-bundled Dataset through the same immutable owner service
/// as browser multipart uploads. Callers provide logical descriptors and
/// trusted checked-in bytes, never a host path.
pub(crate) async fn publish_trusted_bundle(
    state: &AppState,
    auth: &AuthenticatedUser,
    workspace_id: Uuid,
    git: &GitRuntime,
    request: PublishWorkspaceDatasetRequest,
    files: Vec<(WorkspaceDatasetUploadFile, &'static [u8])>,
) -> Result<WorkspaceDatasetReleaseSummary, ApiError> {
    publish_trusted_bytes_bundle(
        state,
        auth,
        workspace_id,
        git,
        request,
        files
            .into_iter()
            .map(|(descriptor, bytes)| (descriptor, bytes.to_vec()))
            .collect(),
    )
    .await
}

/// Publish server-generated bytes through the immutable Dataset Release owner.
/// The bytes are already authorized and bounded by the caller; no host path or
/// browser-provided file reference is accepted.
pub(crate) async fn publish_trusted_bytes_bundle(
    state: &AppState,
    auth: &AuthenticatedUser,
    workspace_id: Uuid,
    git: &GitRuntime,
    request: PublishWorkspaceDatasetRequest,
    files: Vec<(WorkspaceDatasetUploadFile, Vec<u8>)>,
) -> Result<WorkspaceDatasetReleaseSummary, ApiError> {
    let uploaded = files
        .into_iter()
        .map(|(descriptor, bytes)| (descriptor.field_id, UploadedPart { bytes }))
        .collect::<HashMap<_, _>>();
    validate_request(&request, &uploaded)?;
    let prepared = prepare_files(&request, uploaded)?;
    publish_prepared_release(state, auth, workspace_id, git, request, prepared).await
}

async fn publish_prepared_release(
    state: &AppState,
    auth: &AuthenticatedUser,
    workspace_id: Uuid,
    git: &GitRuntime,
    request: PublishWorkspaceDatasetRequest,
    prepared: BTreeMap<String, PreparedFile>,
) -> Result<WorkspaceDatasetReleaseSummary, ApiError> {
    let content_sha256 = release_content_sha256(&request, &prepared);

    if let Some(existing) = find_by_idempotency(
        state,
        auth.organization_id,
        workspace_id,
        &request.idempotency_key,
    )
    .await?
    {
        if existing.content_sha256 != content_sha256
            || existing.dataset_id != request.dataset_id
            || existing.version != request.version
        {
            return Err(conflict(
                "The idempotency key is already bound to different Dataset Release content",
            ));
        }
        return recover_or_retry_existing(
            state,
            auth,
            git,
            &request,
            &prepared,
            &content_sha256,
            &existing,
        )
        .await;
    }

    if let Some(existing) = find_by_identity(
        state,
        auth.organization_id,
        workspace_id,
        &request.dataset_id,
        &request.version,
    )
    .await?
    {
        if existing.content_sha256 != content_sha256 {
            return Err(conflict(
                "This Dataset ID and version is bound to different immutable content",
            ));
        }
        return recover_or_retry_existing(
            state,
            auth,
            git,
            &request,
            &prepared,
            &content_sha256,
            &existing,
        )
        .await;
    }

    let release_id = Uuid::now_v7();
    if let Err(error) = reserve_release(
        state,
        auth,
        workspace_id,
        release_id,
        &request,
        &content_sha256,
        &prepared,
    )
    .await
    {
        if error.0 == StatusCode::CONFLICT {
            let existing = find_by_identity(
                state,
                auth.organization_id,
                workspace_id,
                &request.dataset_id,
                &request.version,
            )
            .await?;
            if let Some(existing) =
                existing.filter(|existing| existing.content_sha256 == content_sha256)
            {
                return recover_or_retry_existing(
                    state,
                    auth,
                    git,
                    &request,
                    &prepared,
                    &content_sha256,
                    &existing,
                )
                .await;
            }
        }
        return Err(error);
    }
    publish_reserved_release(
        state,
        auth,
        git,
        workspace_id,
        &request,
        &prepared,
        release_id,
        &content_sha256,
    )
    .await
}

async fn publish_reserved_release(
    state: &AppState,
    auth: &AuthenticatedUser,
    git: &GitRuntime,
    workspace_id: Uuid,
    request: &PublishWorkspaceDatasetRequest,
    prepared: &BTreeMap<String, PreparedFile>,
    release_id: Uuid,
    content_sha256: &str,
) -> Result<WorkspaceDatasetReleaseSummary, ApiError> {
    let manifest = release_manifest(release_id, request, content_sha256, prepared)?;
    let file_bytes = prepared
        .iter()
        .map(|(logical_name, file)| (logical_name.clone(), file.bytes.clone()))
        .collect::<BTreeMap<_, _>>();

    let written_files = match git
        .publish_dataset_release(
            workspace_id,
            &request.dataset_id,
            &request.version,
            &manifest,
            &file_bytes,
        )
        .await
    {
        Ok(written_files) => written_files,
        Err(error) => {
            let failure_code = git_failure_code(&error);
            mark_failed(state, auth, release_id, workspace_id, failure_code).await?;
            return Err(git_error(error));
        }
    };

    if let Err(error) = mark_published(
        state,
        auth,
        release_id,
        workspace_id,
        &content_sha256,
        written_files.len(),
        "workspace.dataset_release_published",
    )
    .await
    {
        tracing::warn!(
            release_id = %release_id,
            "dataset files were published but database finalization was ambiguous"
        );
        return Err(error);
    }

    load_release(state, auth, workspace_id, release_id)
        .await?
        .ok_or_else(|| internal("Published Dataset Release could not be loaded"))
}

async fn parse_multipart(
    mut multipart: Multipart,
) -> Result<
    (
        PublishWorkspaceDatasetRequest,
        HashMap<String, UploadedPart>,
    ),
    ApiError,
> {
    let mut metadata = None;
    let mut uploaded = HashMap::new();
    let mut total_bytes = 0usize;
    while let Some(field) = multipart
        .next_field()
        .await
        .map_err(|_| bad_request("Dataset upload could not be read"))?
    {
        let field_name = field
            .name()
            .map(str::to_string)
            .ok_or_else(|| bad_request("Every Dataset upload field needs an identifier"))?;
        if field_name == "metadata" {
            if metadata.is_some() {
                return Err(bad_request("Dataset upload metadata was repeated"));
            }
            let bytes = field
                .bytes()
                .await
                .map_err(|_| bad_request("Dataset upload metadata could not be read"))?;
            if bytes.is_empty() || bytes.len() > MAX_METADATA_BYTES {
                return Err(payload_too_large(
                    "Dataset upload metadata exceeds the supported size",
                ));
            }
            metadata = Some(
                serde_json::from_slice::<PublishWorkspaceDatasetRequest>(&bytes)
                    .map_err(|_| bad_request("Dataset upload metadata is invalid"))?,
            );
            continue;
        }
        if uploaded.len() >= MAX_FILES || uploaded.contains_key(&field_name) {
            return Err(bad_request(
                "Dataset upload has too many or duplicate file fields",
            ));
        }
        let bytes = field
            .bytes()
            .await
            .map_err(|_| bad_request("A Dataset file could not be read"))?;
        if bytes.is_empty() {
            return Err(bad_request("Dataset files must not be empty"));
        }
        if bytes.len() > MAX_FILE_BYTES {
            return Err(payload_too_large("A Dataset file exceeds the 32 MiB limit"));
        }
        total_bytes = total_bytes
            .checked_add(bytes.len())
            .ok_or_else(|| payload_too_large("Dataset upload size overflowed"))?;
        if total_bytes > MAX_TOTAL_FILE_BYTES {
            return Err(payload_too_large(
                "Dataset files exceed the 64 MiB total limit",
            ));
        }
        uploaded.insert(
            field_name,
            UploadedPart {
                bytes: bytes.to_vec(),
            },
        );
    }
    Ok((
        metadata.ok_or_else(|| bad_request("Dataset upload metadata is required"))?,
        uploaded,
    ))
}

fn validate_request(
    request: &PublishWorkspaceDatasetRequest,
    uploaded: &HashMap<String, UploadedPart>,
) -> Result<(), ApiError> {
    if request.idempotency_key.len() < 8
        || request.idempotency_key.len() > 128
        || request.idempotency_key.chars().any(char::is_control)
    {
        return Err(bad_request("Dataset idempotency key is invalid"));
    }
    if !valid_slug(&request.dataset_id) {
        return Err(bad_request("Dataset ID is invalid"));
    }
    if !valid_version(&request.version) {
        return Err(bad_request("Dataset version is invalid"));
    }
    if request.display_name.trim().is_empty() || request.display_name.len() > 160 {
        return Err(bad_request("Dataset display name is invalid"));
    }
    if request.description.trim().is_empty() || request.description.len() > 1024 {
        return Err(bad_request("Dataset description is invalid"));
    }
    if request.files.is_empty() || request.files.len() > MAX_FILES {
        return Err(bad_request(
            "A Dataset Release must contain between 1 and 32 files",
        ));
    }
    let mut field_ids = HashSet::new();
    let mut logical_names = HashSet::new();
    for file in &request.files {
        if !valid_field_id(&file.field_id) || !field_ids.insert(file.field_id.as_str()) {
            return Err(bad_request("Dataset file field identifiers are invalid"));
        }
        if !valid_logical_name(&file.logical_name)
            || !logical_names.insert(file.logical_name.as_str())
        {
            return Err(bad_request("Dataset logical file names are invalid"));
        }
        if !valid_role(&file.role) {
            return Err(bad_request("Dataset file role is invalid"));
        }
        if !valid_media_type(&file.media_type) {
            return Err(bad_request("Dataset file media type is invalid"));
        }
    }
    let uploaded_ids = uploaded.keys().map(String::as_str).collect::<HashSet<_>>();
    if uploaded_ids != field_ids {
        return Err(bad_request(
            "Dataset file fields do not match the declared metadata",
        ));
    }
    Ok(())
}

fn prepare_files(
    request: &PublishWorkspaceDatasetRequest,
    mut uploaded: HashMap<String, UploadedPart>,
) -> Result<BTreeMap<String, PreparedFile>, ApiError> {
    let mut prepared = BTreeMap::new();
    for descriptor in &request.files {
        let part = uploaded
            .remove(&descriptor.field_id)
            .ok_or_else(|| bad_request("A declared Dataset file is missing"))?;
        let content_sha256 = hex::encode(Sha256::digest(&part.bytes));
        prepared.insert(
            descriptor.logical_name.clone(),
            PreparedFile {
                descriptor: descriptor.clone(),
                bytes: part.bytes,
                content_sha256,
            },
        );
    }
    Ok(prepared)
}

fn release_content_sha256(
    request: &PublishWorkspaceDatasetRequest,
    files: &BTreeMap<String, PreparedFile>,
) -> String {
    let mut digest = Sha256::new();
    update_digest(&mut digest, "workspace.dataset-release.v1");
    update_digest(&mut digest, &request.dataset_id);
    update_digest(&mut digest, &request.version);
    update_digest(&mut digest, request.display_name.trim());
    update_digest(&mut digest, request.description.trim());
    for (logical_name, file) in files {
        update_digest(&mut digest, logical_name);
        update_digest(&mut digest, &file.descriptor.role);
        update_digest(&mut digest, &file.descriptor.media_type);
        update_digest(&mut digest, &file.bytes.len().to_string());
        update_digest(&mut digest, &file.content_sha256);
    }
    hex::encode(digest.finalize())
}

fn update_digest(digest: &mut Sha256, value: &str) {
    digest.update((value.len() as u64).to_be_bytes());
    digest.update(value.as_bytes());
}

fn release_manifest(
    release_id: Uuid,
    request: &PublishWorkspaceDatasetRequest,
    content_sha256: &str,
    files: &BTreeMap<String, PreparedFile>,
) -> Result<Vec<u8>, ApiError> {
    let files = files
        .iter()
        .map(|(logical_name, file)| {
            json!({
                "logicalName": logical_name,
                "role": file.descriptor.role,
                "mediaType": file.descriptor.media_type,
                "byteSize": file.bytes.len(),
                "contentSha256": file.content_sha256,
                "relativePath": format!("files/{logical_name}"),
            })
        })
        .collect::<Vec<_>>();
    serde_json::to_vec_pretty(&json!({
        "schemaVersion": "workspace.dataset-release.v1",
        "releaseId": release_id,
        "datasetId": request.dataset_id,
        "version": request.version,
        "displayName": request.display_name.trim(),
        "description": request.description.trim(),
        "contentSha256": content_sha256,
        "files": files,
    }))
    .map(|mut manifest| {
        manifest.push(b'\n');
        manifest
    })
    .map_err(|_| internal("Dataset Release manifest could not be created"))
}

async fn reserve_release(
    state: &AppState,
    auth: &AuthenticatedUser,
    workspace_id: Uuid,
    release_id: Uuid,
    request: &PublishWorkspaceDatasetRequest,
    content_sha256: &str,
    files: &BTreeMap<String, PreparedFile>,
) -> Result<(), ApiError> {
    let mut transaction = state.db.begin().await.map_err(database_error)?;
    let insert = sqlx::query(
        "INSERT INTO workspace_dataset_releases \
         (id, organization_id, workspace_id, owner_user_id, idempotency_key, \
          dataset_id, version, display_name, description, state, content_sha256) \
         VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9, 'publishing', $10)",
    )
    .bind(release_id)
    .bind(auth.organization_id)
    .bind(workspace_id)
    .bind(auth.user_id)
    .bind(&request.idempotency_key)
    .bind(&request.dataset_id)
    .bind(&request.version)
    .bind(request.display_name.trim())
    .bind(request.description.trim())
    .bind(content_sha256)
    .execute(&mut *transaction)
    .await;
    if let Err(error) = insert {
        transaction.rollback().await.ok();
        if error
            .as_database_error()
            .is_some_and(sqlx::error::DatabaseError::is_unique_violation)
        {
            return Err(conflict(
                "The Dataset Release identity or idempotency key already exists",
            ));
        }
        return Err(database_error(error));
    }
    for (logical_name, file) in files {
        sqlx::query(
            "INSERT INTO workspace_dataset_release_files \
             (organization_id, release_id, logical_name, role, media_type, byte_size, \
              content_sha256) VALUES ($1, $2, $3, $4, $5, $6, $7)",
        )
        .bind(auth.organization_id)
        .bind(release_id)
        .bind(logical_name)
        .bind(&file.descriptor.role)
        .bind(&file.descriptor.media_type)
        .bind(file.bytes.len() as i64)
        .bind(&file.content_sha256)
        .execute(&mut *transaction)
        .await
        .map_err(database_error)?;
    }
    audit(
        &mut transaction,
        auth,
        release_id,
        "workspace.dataset_release_started",
        "success",
        json!({
            "workspaceId": workspace_id,
            "datasetId": request.dataset_id,
            "version": request.version,
            "contentSha256": content_sha256,
            "fileCount": files.len(),
        }),
    )
    .await?;
    transaction.commit().await.map_err(database_error)
}

async fn recover_or_retry_existing(
    state: &AppState,
    auth: &AuthenticatedUser,
    git: &GitRuntime,
    request: &PublishWorkspaceDatasetRequest,
    prepared: &BTreeMap<String, PreparedFile>,
    content_sha256: &str,
    release: &ReleaseRecord,
) -> Result<WorkspaceDatasetReleaseSummary, ApiError> {
    let matches = git
        .dataset_release_matches(
            release.workspace_id,
            &release.dataset_id,
            &release.version,
            release.id,
            &release.content_sha256,
        )
        .await
        .map_err(git_error)?;
    let recovery_due =
        Utc::now() - release.updated_at >= Duration::minutes(PUBLISHING_RECOVERY_AFTER_MINUTES);
    match existing_release_action(&release.state, matches, recovery_due) {
        ExistingReleaseAction::ReturnPublished => {}
        ExistingReleaseAction::FinalizePublished => {
            if release.state == "failed" {
                claim_failed_for_retry(state, auth, release).await?;
            }
            mark_published(
                state,
                auth,
                release.id,
                release.workspace_id,
                &release.content_sha256,
                0,
                "workspace.dataset_release_recovered",
            )
            .await?;
        }
        ExistingReleaseAction::RetryPublication => {
            if release.state == "publishing" {
                mark_failed(
                    state,
                    auth,
                    release.id,
                    release.workspace_id,
                    "publication_interrupted",
                )
                .await?;
            }
            claim_failed_for_retry(state, auth, release).await?;
            return publish_reserved_release(
                state,
                auth,
                git,
                release.workspace_id,
                request,
                prepared,
                release.id,
                content_sha256,
            )
            .await;
        }
        ExistingReleaseAction::PublicationInProgress => {
            return Err(conflict("Dataset Release publication is still in progress"));
        }
        ExistingReleaseAction::PublishedContentUnavailable => {
            return Err(conflict(
                "Published Dataset Release content is missing or changed",
            ));
        }
        ExistingReleaseAction::InvalidLifecycle => {
            return Err(conflict(
                "Dataset Release has an unsupported lifecycle state",
            ));
        }
    }

    load_release(state, auth, release.workspace_id, release.id)
        .await
        .and_then(|release| {
            release.ok_or_else(|| internal("Dataset Release could not be restored"))
        })
}

fn existing_release_action(
    state: &str,
    content_matches: bool,
    recovery_due: bool,
) -> ExistingReleaseAction {
    match (state, content_matches, recovery_due) {
        ("published", true, _) => ExistingReleaseAction::ReturnPublished,
        ("published", false, _) => ExistingReleaseAction::PublishedContentUnavailable,
        ("publishing", true, _) | ("failed", true, _) => ExistingReleaseAction::FinalizePublished,
        ("publishing", false, false) => ExistingReleaseAction::PublicationInProgress,
        ("publishing", false, true) | ("failed", false, _) => {
            ExistingReleaseAction::RetryPublication
        }
        _ => ExistingReleaseAction::InvalidLifecycle,
    }
}

async fn claim_failed_for_retry(
    state: &AppState,
    auth: &AuthenticatedUser,
    release: &ReleaseRecord,
) -> Result<(), ApiError> {
    let mut transaction = state.db.begin().await.map_err(database_error)?;
    let updated = sqlx::query(
        "UPDATE workspace_dataset_releases \
         SET state = 'publishing', failure_code = NULL, updated_at = now() \
         WHERE id = $1 AND organization_id = $2 AND workspace_id = $3 \
           AND state = 'failed' AND content_sha256 = $4",
    )
    .bind(release.id)
    .bind(auth.organization_id)
    .bind(release.workspace_id)
    .bind(&release.content_sha256)
    .execute(&mut *transaction)
    .await
    .map_err(database_error)?
    .rows_affected();
    if updated != 1 {
        transaction.rollback().await.ok();
        return Err(conflict(
            "Dataset Release recovery was changed by another request",
        ));
    }
    audit(
        &mut transaction,
        auth,
        release.id,
        "workspace.dataset_release_retry_started",
        "success",
        json!({
            "workspaceId": release.workspace_id,
            "contentSha256": release.content_sha256,
        }),
    )
    .await?;
    transaction.commit().await.map_err(database_error)
}

async fn mark_published(
    state: &AppState,
    auth: &AuthenticatedUser,
    release_id: Uuid,
    workspace_id: Uuid,
    content_sha256: &str,
    written_file_count: usize,
    action: &str,
) -> Result<(), ApiError> {
    let mut transaction = state.db.begin().await.map_err(database_error)?;
    let result = sqlx::query(
        "UPDATE workspace_dataset_releases \
         SET state = 'published', published_at = now(), updated_at = now() \
         WHERE id = $1 AND organization_id = $2 AND workspace_id = $3 \
           AND state = 'publishing' AND content_sha256 = $4",
    )
    .bind(release_id)
    .bind(auth.organization_id)
    .bind(workspace_id)
    .bind(content_sha256)
    .execute(&mut *transaction)
    .await
    .map_err(database_error)?;
    if result.rows_affected() != 1 {
        let current = sqlx::query(
            "SELECT state, content_sha256 FROM workspace_dataset_releases \
             WHERE id = $1 AND organization_id = $2 AND workspace_id = $3",
        )
        .bind(release_id)
        .bind(auth.organization_id)
        .bind(workspace_id)
        .fetch_optional(&mut *transaction)
        .await
        .map_err(database_error)?;
        transaction.rollback().await.ok();
        if current.is_some_and(|row| {
            row.get::<String, _>("state") == "published"
                && row.get::<String, _>("content_sha256") == content_sha256
        }) {
            return Ok(());
        }
        return Err(conflict(
            "Dataset Release no longer has a publishable lifecycle state",
        ));
    }
    audit(
        &mut transaction,
        auth,
        release_id,
        action,
        "success",
        json!({
            "workspaceId": workspace_id,
            "contentSha256": content_sha256,
            "writtenFileCount": written_file_count,
        }),
    )
    .await?;
    transaction.commit().await.map_err(database_error)
}

async fn mark_failed(
    state: &AppState,
    auth: &AuthenticatedUser,
    release_id: Uuid,
    workspace_id: Uuid,
    failure_code: &str,
) -> Result<(), ApiError> {
    let mut transaction = state.db.begin().await.map_err(database_error)?;
    let updated = sqlx::query(
        "UPDATE workspace_dataset_releases \
         SET state = 'failed', failure_code = $4, updated_at = now() \
         WHERE id = $1 AND organization_id = $2 AND workspace_id = $3 \
           AND state = 'publishing'",
    )
    .bind(release_id)
    .bind(auth.organization_id)
    .bind(workspace_id)
    .bind(failure_code)
    .execute(&mut *transaction)
    .await
    .map_err(database_error)?
    .rows_affected();
    if updated != 1 {
        let current = sqlx::query_scalar::<_, String>(
            "SELECT state FROM workspace_dataset_releases \
             WHERE id = $1 AND organization_id = $2 AND workspace_id = $3",
        )
        .bind(release_id)
        .bind(auth.organization_id)
        .bind(workspace_id)
        .fetch_optional(&mut *transaction)
        .await
        .map_err(database_error)?;
        transaction.rollback().await.ok();
        if current.as_deref() == Some("failed") {
            return Ok(());
        }
        return Err(conflict(
            "Dataset Release no longer permits a failure transition",
        ));
    }
    audit(
        &mut transaction,
        auth,
        release_id,
        "workspace.dataset_release_failed",
        "failure",
        json!({
            "workspaceId": workspace_id,
            "failureCode": failure_code,
        }),
    )
    .await?;
    transaction.commit().await.map_err(database_error)
}

